# --- machinery (shapes verbatim from _07/_09) ----------------
struct TWorld; inputs::Vector{Vector{Int}}; end
nmarks(w::TWorld) = length(w.inputs)
defect(w, s, i, m) = mod(s[i] - sum(s[w.inputs[i]]; init=0) - 1, m)
charge(w, s, m)    = mod(sum(defect(w, s, i, m) for i in 1:nmarks(w)), m)
outdeg(w) = (d = zeros(Int, nmarks(w));
             for ins in w.inputs, j in ins; d[j] += 1; end; d)
all_states(m, n) = (digits(c, base=m, pad=n) for c in 0:(m^n - 1))

# coefficient vector d_j = 1 − outdeg j
coeffs(w) = 1 .- outdeg(w)

# predicted image size from (★): m / gcd(d_1,…,d_n, m)
image_pred(w, m) = m ÷ gcd(m, gcd(coeffs(w)...))

image_actual(w, m) = length(Set(charge(w, collect(s), m) for s in all_states(m, nmarks(w))))

